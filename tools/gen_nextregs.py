"""Write src/nextregs_reset.inc from Hart's-tongue Fern's machine/nextregs.tsv (core 3.02.02): each Next register's
hard- and soft-reset value as the table gives it, so nextcore.cpp's reset values are generated, not typed.
Only plain values are taken ("0x0A", "0x00 (a note)", "0", "reads 0x90", "same" = the other column); anything descriptive is left
for a handler in nextcore.cpp to compute from the machine's state, and listed in the .inc as such.
Usage: python3 tools/gen_nextregs.py PATH/TO/nextregs.tsv > src/nextregs_reset.inc"""
import csv, re, sys
rows = list(csv.DictReader(open(sys.argv[1]), delimiter='\t'))
def plain(s):
    s = s.strip()
    m = re.fullmatch(r'(?:reads |out )?0x([0-9A-Fa-f]{1,2})(?: \([^()]*\))?', s)   # a value, maybe with a note
    if m:
        return int(m[1], 16)
    if s == '0':
        return 0
    return None
print('// Generated by tools/gen_nextregs.py from machine/nextregs.tsv (core 3.02.02): do not edit.')
print('// { reg, hard, soft }: -1 hard = not a plain value (a handler computes it); -1 soft = unchanged by a soft reset.')
print('static const struct { int reg, hard, soft; } NR_RESET[] = {')
left = []
for r in rows:
    try:
        reg = int(r['reg'], 16)
    except ValueError:
        continue
    hard_s, soft_s = r['hard_reset'].strip(), r['soft_reset'].strip()
    hard = plain(hard_s)
    soft = plain(soft_s)
    if hard_s == 'same' and soft is not None:
        hard = soft
    if soft_s == 'same' and hard is not None:
        soft = hard
    if soft_s in ('unchanged', '-') or soft is None:
        soft = -1
    if hard is None:
        left.append(f"0x{reg:02X} ({r['name']}): hard '{hard_s}', soft '{soft_s}'")
        hard = -1
    print(f"    {{0x{reg:02X}, {hard}, {soft}}},   // {r['name']}")
print('};')
print('// Left for handlers (not plain values in the table):')
for l in left:
    print('//   ' + l)
