"""Build LDPIRX2.TAP: the follow-up to Z80NTIME's one miss. Strobe Fern, Fri 6 Nov 2026.

  build_ldpirx2.py          writes ldpirx2.asm, build/ldpirx2.bin, build/LDPIRX2.TAP

On the test machine, Z80NTIME's LDPIRX flags cell read 00 where the VHDL (as I read it) says 08. With F = 00
going in that has two readings: LDPIRX leaves the flags alone, or the byte the CPU saw wasn't the pattern byte
(DE's byte was 00 there). This tape tells them apart: F = FF going in (so "left alone" shows FF), different
bytes at the pattern address, at plain HL and at DE, and the byte LDPIRX wrote at DE printed beside the flags.
Each case runs at 3.5 MHz and again at 28 MHz. Interrupts off; nothing timed; returns to BASIC.

The scratch page BB00h-BBFFh: zeros, then BB30h-BB37h = 80h..87h (the pattern row), with changes per case.
  C1  A=02 F=FF BC=1 HL=BB35 DE=BB82: pattern BB32 = 48h, (HL) = 85h, (DE) = 22h
  C2  the Z80NTIME test again: A=02 F=00 BC=1 HL=BB30 (08h) DE=BB68 (00h)
  C3  C1 with F=00
  C5  a control: LDIX (not LDPIRX) on C1's layout
  C6  BIT 0,(IX+5) (DD CB 05 46) at BB35h holding 85h, F=00: T80N 10 (X, Y = 0); a Zilog 38 (MEMPTR BBh)
  C7  the undocumented DD CB 05 40 at 9045h holding 29h, F=00: T80N 38 (X, Y from the byte); a Zilog 10 (90h)
What each explanation prints (F, then the byte at DE afterwards):
  C1  VHDL as read C9 48; flags left alone FF 48; from A+byte E9 48; byte from DE E1 22; from plain HL C1 85
  C2  VHDL 08 08; left alone 00 08; byte from DE 00 00
  C3  VHDL 08 48; left alone 00 48; byte from DE 20 22
  C5  LDIX: E1 85 (n = A + 85h = 87h: Y, not X)
"""
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from build_probe import PASMO, tap_block, header, num, check_tap  # noqa: E402

ASM = r'''; ldpirx2.asm: generated by build_ldpirx2.py (Strobe Fern, Fri 6 Nov 2026). See its docstring.
PREG    EQU 0x243B
SCR     EQU 0xBB00

        org 0x8000
start:  di
        ld (bas_sp),sp
        ld sp,0xBD00            ; (above the scratch page BB00h-BBFFh)
        ld a,0x07
        call nr_read
        ld (sv07),a
        ld a,0x01
        call nr_read
        ld (sv01),a
        ld a,0x0E
        call nr_read
        ld (sv0e),a
        ld a,0x07               ; 3.5 MHz (nextregs through the ports: harmless without them)
        ld e,0
        call nr_write
        ld hl,res35
        call runall
        ld a,0x07               ; 28 MHz
        ld e,3
        call nr_write
        ld a,0x07
        call nr_read
        ld (sp28),a
        ld hl,res28
        call runall
        ld a,(sv07)
        and 3
        ld e,a
        ld a,0x07
        call nr_write
        call report
        call photobeep          ; the photo beep (Melissa O'Neill's idea, Tally Fern's spec; ../beep.inc), added by Hart's-tongue
        call waitkey            ; a photo, then a key (Melissa O'Neill's rule)
        ld sp,(bas_sp)
        ei
        ret

nr_write:                       ; nextreg A = E
        ld bc,PREG
        out (c),a
        inc b
        out (c),e
        ret

nr_read:                        ; A = nextreg A
        ld bc,PREG
        out (c),a
        inc b
        in a,(c)
        ret

waitkey:                        ; any key, through port FEh (interrupts off): let go first, then a press
        xor a
        in a,(0xFE)
        cpl
        and 0x1F
        jr nz,waitkey
wk1:    xor a
        in a,(0xFE)
        cpl
        and 0x1F
        jr z,wk1
        ret

runall: ld (rptr),hl            ; the four cases; each leaves (cf) = F, (cb) = the byte at DE
        call case1
        call store
        call case2
        call store
        call case3
        call store
        call case5
        call store
        call case6
        call store
        call case7
        call store
        ret

store:  ld hl,(rptr)
        ld a,(cf)
        ld (hl),a
        inc hl
        ld a,(cb)
        ld (hl),a
        inc hl
        ld (rptr),hl
        ret

fillscr:                        ; zeros, then BB30h-BB37h = 80h..87h
        ld hl,SCR
        ld de,SCR+1
        ld bc,255
        ld (hl),0
        ldir
        ld hl,SCR+0x30
        ld a,0x80
        ld b,8
fs1:    ld (hl),a
        inc hl
        inc a
        djnz fs1
        ret

case1:  call fillscr
        ld a,0x48
        ld (SCR+0x32),a
        ld a,0x22
        ld (SCR+0x82),a
        ld hl,0x02FF            ; A = 02h, F = FFh
        push hl
        pop af
        ld hl,SCR+0x35
        ld de,SCR+0x82
        ld bc,1
        db 0xED,0xB7            ; LDPIRX
        push af
        pop hl
        ld a,l
        ld (cf),a
        ld a,(SCR+0x82)
        ld (cb),a
        ret

case2:  call fillscr
        ld a,0x08
        ld (SCR+0x30),a
        ld hl,0x0200            ; A = 02h, F = 00h
        push hl
        pop af
        ld hl,SCR+0x30
        ld de,SCR+0x68
        ld bc,1
        db 0xED,0xB7
        push af
        pop hl
        ld a,l
        ld (cf),a
        ld a,(SCR+0x68)
        ld (cb),a
        ret

case3:  call fillscr
        ld a,0x48
        ld (SCR+0x32),a
        ld a,0x22
        ld (SCR+0x82),a
        ld hl,0x0200            ; A = 02h, F = 00h
        push hl
        pop af
        ld hl,SCR+0x35
        ld de,SCR+0x82
        ld bc,1
        db 0xED,0xB7
        push af
        pop hl
        ld a,l
        ld (cf),a
        ld a,(SCR+0x82)
        ld (cb),a
        ret

case5:  call fillscr
        ld a,0x48
        ld (SCR+0x32),a
        ld a,0x22
        ld (SCR+0x82),a
        ld hl,0x02FF
        push hl
        pop af
        ld hl,SCR+0x35
        ld de,SCR+0x82
        ld bc,1
        db 0xED,0xA4            ; LDIX
        push af
        pop hl
        ld a,l
        ld (cf),a
        ld a,(SCR+0x82)
        ld (cb),a
        ret

case6:  ld a,0x85                ; BIT 0,(IX+5) at BB35h (high byte BBh: bits 5, 3 set), F = 00h
        ld (SCR+0x35),a
        ld hl,0x0000
        push hl
        pop af
        ld ix,SCR+0x30
        db 0xDD,0xCB,0x05,0x46
        jr bitres
case7:  ld a,0x29                ; the undocumented DD CB d 40 at 9045h (high byte 90h: bits 5, 3 clear)
        ld (0x9045),a
        ld hl,0x0000
        push hl
        pop af
        ld ix,0x9040
        db 0xDD,0xCB,0x05,0x40
bitres: push af
        pop hl
        ld a,l
        ld (cf),a
        xor a
        ld (cb),a
        ret

; -- printing ---------------------------------------------------------------------------------------
cls:    call 0x0DAF
        ld a,2
        call 0x1601
        ld a,255
        ld (0x5C8C),a
        ret

putc:   push bc                 ; A to the screen (A comes back changed)
        push de
        push hl
        rst 0x10
        pop hl
        pop de
        pop bc
        ret

pstr:   ld a,(hl)
        or a
        ret z
        call putc
        inc hl
        jr pstr

phex2:  push af
        rrca
        rrca
        rrca
        rrca
        call phex1
        pop af
phex1:  and 15
        add a,0x90
        daa
        adc a,0x40
        daa
        jp putc

pdec2z: ld b,'0'-1
pz1:    inc b
        sub 10
        jr nc,pz1
        add a,10+'0'
        push af
        ld a,b
        call putc
        pop af
        jp putc

report: call cls
        ld hl,s_t1
        call pstr
        ld a,(sv01)
        rrca
        rrca
        rrca
        rrca
        and 15
        add a,'0'
        call putc
        ld a,'.'
        call putc
        ld a,(sv01)
        and 15
        call pdec2z
        ld a,'.'
        call putc
        ld a,(sv0e)
        call pdec2z
        ld hl,s_t2
        call pstr
        ld a,(sp28)
        call phex2
        ld hl,s_hd
        call pstr
        ld hl,s_lab             ; four rows: "Cn    FF BB   FF BB"
        ld de,res35
        ld ix,res28
        ld b,6
rp1:    push bc
        call pstr               ; the label (advances HL past its 0)
        inc hl
        push hl
        ld a,(de)
        call phex2
        ld a,' '
        call putc
        inc de
        ld a,(de)
        call phex2
        inc de
        ld a,' '
        call putc
        ld a,' '
        call putc
        ld a,' '
        call putc
        ld a,(ix+0)
        call phex2
        ld a,' '
        call putc
        ld a,(ix+1)
        call phex2
        inc ix
        inc ix
        ld a,13
        call putc
        pop hl
        pop bc
        djnz rp1
        ld hl,s_leg
        jp pstr

s_t1:   db "LDPIRX2 (Strobe) core ",0
s_t2:   db 13,"F, then the byte at DE; cpu28 ",0
s_hd:   db 13,"      3.5 MHz  28 MHz",13,0
s_lab:  db "C1    ",0,"C2    ",0,"C3    ",0,"C5    ",0,"C6    ",0,"C7    ",0
s_leg:  db 13,"what each would print:",13
        db "C1 VHDL C9 48  untouched FF 48",13
        db "   A+byte E9 48  DE's E1 22",13
        db "   plain HL's C1 85",13
        db "C2 VHDL 08 08  untouched 00 08",13
        db "   DE's 00 00",13
        db "C3 VHDL 08 48  untouched 00 48",13
        db "   DE's 20 22",13
        db "C5 (LDIX, a control) E1 85",13
        db "C6 BIT (IX+d) T80N 10 Zilog 38",13
        db "C7 DDCB 40: T80N 38 Zilog 10",13
        db "photo, then press a key",0

sv07:   db 0
sv01:   db 0
sv0e:   db 0
sp28:   db 0
bas_sp: dw 0
rptr:   dw 0
cf:     db 0
cb:     db 0
res35:  ds 12
res28:  ds 12

TAPEID  equ 62                ; the photo beep's tape ID (../NOTES.md, "The photo beep")
        include "../beep.inc"
'''


def main():
    (HERE / 'ldpirx2.asm').write_text(ASM)
    out = HERE / 'build'
    out.mkdir(exist_ok=True)
    r = subprocess.run([str(PASMO), '--bin', 'ldpirx2.asm', str(out / 'ldpirx2.bin'), str(out / 'ldpirx2.sym')],
                       cwd=HERE, capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stdout + r.stderr)
    code = (out / 'ldpirx2.bin').read_bytes()
    line = bytes([0xFD]) + num(32767) + b':' + bytes([0xEF]) + b'""' + bytes([0xAF]) + b':' + \
        bytes([0xF9, 0xC0]) + num(32768) + b'\r'
    prog = (10).to_bytes(2, 'big') + len(line).to_bytes(2, 'little') + line
    tap = header(0, 'ldpirx2', len(prog), 10, len(prog)) + tap_block(0xFF, prog)
    tap += header(3, 'ldpirx2c', len(code), 32768, 32768) + tap_block(0xFF, code)
    blocks = check_tap(tap)
    (out / 'LDPIRX2.TAP').write_bytes(tap)
    print(f'LDPIRX2.TAP: {len(tap)} bytes, {blocks} blocks, checksums good (code {len(code)}, to '
          f'{0x8000 + len(code):04X})')


if __name__ == '__main__':
    main()
