"""Build Z80NFLAG.TAP: the flags where the Next's CPU (the T80N) and a Zilog Z80 part company. Strobe Fern, Fri 6 Nov 2026.

  build_flags2.py          writes z80nflag.asm, build/z80nflag.bin, build/Z80NFLAG.TAP

The Next's core has a second CPU, t80n-complete, "with the memptr and xy flags fixes applied" and not switched on
(the 3.02.04 changelog). The difference between the two is a list of every place the Next's own T80N leaves a
Zilog: BIT's X and Y (already probed: BITF, C6, C7), and four more, which this tape asks about:
  INI/IND/OUTI/OUTD (and repeats): the T80N leaves SUB B,1's flags; a Zilog takes N from the byte's bit 7, H and C
      from a carry, and P from a parity (floooh's z80.h, and so omse-ai today, does the Zilog's);
  CPI/CPD (and repeats): the T80N takes X and Y from the byte's bits 3 and 5; a Zilog from bits 3 and 1 of
      A - byte - H;
  LD A,I and LD A,R: the T80N leaves X and Y as they were; a Zilog copies I's (or R's) bits 5 and 3;
  IN r,(C): the T80N leaves X and Y as they were; a Zilog copies the byte's.
Each cell starts with F = 00h and prints what F became, what the T80N's VHDL says, and what a Zilog gives. Ports
come from nextreg 7Fh (user register 0) through port 253Bh, set first through the ports; everything is put back.
Interrupts off; one screen; "photo, then press a key"; returns to BASIC.
"""
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from build_probe import PASMO, tap_block, header, num, check_tap  # noqa: E402

SCR = 0xBB00
CELLS = [  # (label (8), code, T80N's F, a Zilog's F)
    ('INI     ', f'''ld a,0x7F
        ld e,0xD0
        call nr_write           ; the port's byte: D0h
        ld hl,{SCR + 0x90}
        ld bc,0x253B
        ld de,0
        push de
        pop af
        db 0xED,0xA2            ; INI''', 0x22, 0x33),
    ('OUTI    ', f'''ld hl,{SCR + 0xF0}
        ld (hl),0x90
        ld bc,0x253B            ; B-1 = 24h first: out to 243Bh, harmless
        ld de,0
        push de
        pop af
        db 0xED,0xA3            ; OUTI''', 0x22, 0x33),
    ('CPI     ', f'''ld hl,{SCR + 0xA0}
        ld (hl),0x28
        ld bc,2
        ld de,0x1000            ; A = 10h, F = 00h
        push de
        pop af
        db 0xED,0xA1            ; CPI''', 0xBE, 0xB6),
    ('LD A,I  ', '''ld a,i
        ld (savi),a
        ld a,0x28
        ld i,a
        ld de,0
        push de
        pop af
        ld a,i
        push af
        ld a,(savi)
        ld i,a
        pop af''', 0x00, 0x28),
    ('IN A,(C)', '''ld a,0x7F
        ld e,0x28
        call nr_write           ; the port's byte: 28h
        ld bc,0x253B
        ld de,0
        push de
        pop af
        in a,(c)''', 0x04, 0x2C),
]

ASM = r'''; {LOWER}.asm: generated by build_flags2.py (Strobe Fern, Fri 6 Nov 2026). See its docstring.
PREG    EQU 0x243B

        org 0x8000
start:  di
        ld (bas_sp),sp
        ld sp,0xBD00
        ld a,0x01
        call nr_read
        ld (sv01),a
        ld a,0x0E
        call nr_read
        ld (sv0e),a
        ld a,0x7F
        call nr_read
        ld (sv7f),a
{CALLS}
{RESTORE}        ld a,(sv7f)             ; put user register 0 back, and select it as Z80NTIME leaves it
        ld e,a
        ld a,0x7F
        call nr_write
        call report
        call photobeep          ; the photo beep (../beep.inc), so find_photos.py can label the frame
        call waitkey
        ld sp,(bas_sp)
        ei
        ret

nr_write:                       ; nextreg A = E
        ld bc,PREG
        out (c),a
        inc b
        out (c),e
        ret

nr_read:
        ld bc,PREG
        out (c),a
        inc b
        in a,(c)
        ret

waitkey:
        xor a
        in a,(0xFE)
        cpl
        and 0x1F
        jr nz,waitkey
wk1:    xor a
        in a,(0xFE)
        cpl
        and 0x1F
        jr z,wk1
        ret

{CELLS}

cls:    call 0x0DAF
        ld a,2
        call 0x1601
        ld a,255
        ld (0x5C8C),a
        ret

putc:   push bc
        push de
        push hl
        rst 0x10
        pop hl
        pop de
        pop bc
        ret

pstr:   ld a,(hl)
        or a
        ret z
        call putc
        inc hl
        jr pstr

phex2:  push af
        rrca
        rrca
        rrca
        rrca
        call phex1
        pop af
phex1:  and 15
        add a,0x90
        daa
        adc a,0x40
        daa
        jp putc

pdec2z: ld b,'0'-1
pz1:    inc b
        sub 10
        jr nc,pz1
        add a,10+'0'
        push af
        ld a,b
        call putc
        pop af
        jp putc

report: call cls
        ld hl,s_t1
        call pstr
        ld a,(sv01)
        rrca
        rrca
        rrca
        rrca
        and 15
        add a,'0'
        call putc
        ld a,'.'
        call putc
        ld a,(sv01)
        and 15
        call pdec2z
        ld a,'.'
        call putc
        ld a,(sv0e)
        call pdec2z
        ld hl,s_t2
        call pstr
        ld ix,tab               ; label (8), then F: got, the T80N's, a Zilog's
        ld de,fres
        ld b,{N}
rp1:    push bc
        push ix
        pop hl
        call pstr
        inc hl
        push hl
        ld a,' '
        call putc
        ld a,(de)
        call phex2
        inc de
        ld hl,s_sep
        call pstr
        pop hl
        ld a,(hl)
        call phex2
        inc hl
        push hl
        ld hl,s_sep
        call pstr
        pop hl
        ld a,(hl)
        call phex2
        inc hl
        push hl
        pop ix
        ld a,13
        call putc
        pop bc
        djnz rp1
        ld hl,s_leg
        jp pstr

s_t1:   db "{NAME} (Strobe) core ",0
s_t2:   db 13,"F from {FROM}: got / T80N / Zilog",13,13,0
s_sep:  db " / ",0
s_leg:  db 13,"T80N: the Next's CPU as its VHDL",13
        db "Zilog: and omse-ai today",13,13
        db "photo, then press a key",0
tab:
{TAB}
sv01:   db 0
sv0e:   db 0
sv7f:   db 0
savi:   db 0
bas_sp: dw 0
fres:   ds {N}
TAPEID  equ {TAPEID}                ; the photo beep's tape ID (../NOTES.md, "The photo beep")
        include "../beep.inc"
'''


def build(name, cells_in, tapeid, frm, restore=''):
    """Write <name>.asm, build/<name>.bin and build/<NAME>.TAP from the cells (Z80NFLAG's layout; build_flags3.py
    uses it too)."""
    CELLS, lower = cells_in, name.lower()
    calls = '\n'.join(f'        call cell{k}' for k in range(len(CELLS)))
    cells = []
    for k, (label, code, t80n, zilog) in enumerate(CELLS):
        cells.append(f'cell{k}:  {code}\n        push af\n        pop hl\n        ld a,l\n        ld (fres+{k}),a\n'
                     f'        ret')
    tab = '\n'.join(f'        db "{label}",0,{t80n},{z}' for label, _, t80n, z in CELLS)
    asm = (ASM.replace('{CALLS}', calls).replace('{CELLS}', '\n'.join(cells)).replace('{TAB}', tab)
           .replace('{N}', str(len(CELLS))).replace('{RESTORE}', restore).replace('{NAME}', name)
           .replace('{FROM}', frm).replace('{TAPEID}', str(tapeid)).replace('{LOWER}', lower))
    (HERE / f'{lower}.asm').write_text(asm)
    out = HERE / 'build'
    out.mkdir(exist_ok=True)
    r = subprocess.run([str(PASMO), '--bin', f'{lower}.asm', str(out / f'{lower}.bin'), str(out / f'{lower}.sym')],
                       cwd=HERE, capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stdout + r.stderr)
    code = (out / f'{lower}.bin').read_bytes()
    line = bytes([0xFD]) + num(32767) + b':' + bytes([0xEF]) + b'""' + bytes([0xAF]) + b':' + \
        bytes([0xF9, 0xC0]) + num(32768) + b'\r'
    prog = (10).to_bytes(2, 'big') + len(line).to_bytes(2, 'little') + line
    tap = header(0, lower, len(prog), 10, len(prog)) + tap_block(0xFF, prog)
    tap += header(3, lower + 'c', len(code), 32768, 32768) + tap_block(0xFF, code)
    blocks = check_tap(tap)
    (out / f'{name}.TAP').write_bytes(tap)
    print(f'{name}.TAP: {len(tap)} bytes, {blocks} blocks, checksums good (code {len(code)}, to '
          f'{0x8000 + len(code):04X})')


def main():
    build('Z80NFLAG', CELLS, 64, '00')


if __name__ == '__main__':
    main()
