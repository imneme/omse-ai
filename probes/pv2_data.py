"""Write pv2_data.inc (db tables for pv2.asm) from pv2_scene.py: the sprite palette (256 NR 0x41 values),
the patterns (bytes for port 0x5B), the sprite records (index, count, attribute bytes; ends with FF), and the
copper words (MSB first, ending FFFF). Hatch Fern, Fri 6 Nov 2026."""
from pathlib import Path
import pv2_scene as sc

HERE = Path(__file__).resolve().parent


def db(label, data):
    lines = [f'{label}:']
    for i in range(0, len(data), 16):
        lines.append('        db ' + ','.join(f'0x{b:02X}' for b in data[i:i + 16]))
    return '\n'.join(lines)


def main():
    pal = sc.sprite_palette()
    pats = [b for p in sc.PATTERNS for b in p]
    recs = []
    for idx, attrs in sorted(sc.sprites().items()):
        recs += [idx, len(attrs)] + attrs
    recs.append(0xFF)
    cop = [b for w in sc.copper_words() for b in (w >> 8, w & 0xFF)]
    out = ['; pv2_data.inc: generated by pv2_data.py from pv2_scene.py; do not edit.',
           f'NPATBYTES equ {len(pats)}', f'CLIPX1 equ {sc.CLIP19[0]}', f'CLIPX2 equ {sc.CLIP19[1]}',
           f'CLIPY1 equ {sc.CLIP19[2]}', f'CLIPY2 equ {sc.CLIP19[3]}', f'NR15V equ 0x{sc.NR15:02X}',
           db('t_pal', pal), db('t_pats', pats), db('t_sprites', recs), db('t_copper', cop)]
    (HERE / 'pv2_data.inc').write_text('\n'.join(out) + '\n')
    print(f'pv2_data.inc: palette 256, patterns {len(pats)}, sprite records {len(recs)}, copper {len(cop)} bytes')


if __name__ == '__main__':
    main()
