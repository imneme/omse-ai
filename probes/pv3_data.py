"""Write pv3_data.inc (db tables for pv3.asm) from pv3_scene.py: the register pairs (FF ends), the patterns
(bytes for port 0x5B), the sprite records (index, count, attribute bytes; FF ends), the copper words (MSB
first, ending FFFF) and the 768 attribute bytes. Hatch Fern, Fri 6 Nov 2026."""
from pathlib import Path
import pv3_scene as sc

HERE = Path(__file__).resolve().parent


def db(label, data):
    lines = [f'{label}:']
    for i in range(0, len(data), 16):
        lines.append('        db ' + ','.join(f'0x{b:02X}' for b in data[i:i + 16]))
    return '\n'.join(lines)


def main():
    regs = [b for pair in sc.regs() for b in pair] + [0xFF]
    assert all(r != 0xFF for r, _ in sc.regs())
    pats = [b for p in sc.PATTERNS for b in p]
    recs = []
    for idx, attrs in sorted(sc.sprites().items()):
        recs += [idx, len(attrs)] + attrs
    recs.append(0xFF)
    words = sc.copper_words()
    assert all(w & 0xFF != 0xFF for w in words[:-1]), 'the copy loop stops at a low byte of FF'
    cop = [b for w in words for b in (w >> 8, w & 0xFF)]
    _, at = sc.ula()
    out = ['; pv3_data.inc: generated by pv3_data.py from pv3_scene.py; do not edit.',
           f'NPATBYTES equ {len(pats)}', db('t_regs', regs), db('t_pats', pats), db('t_sprites', recs),
           db('t_copper', cop), db('t_attr', list(at))]
    (HERE / 'pv3_data.inc').write_text('\n'.join(out) + '\n')
    print(f'pv3_data.inc: regs {len(regs)}, patterns {len(pats)}, sprite records {len(recs)}, '
          f'copper {len(cop)}, attributes {len(at)} bytes')


if __name__ == '__main__':
    main()
