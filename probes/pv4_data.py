"""Write pv4_data.inc (db tables for pv4.asm) from pv4_scene.py: the register pairs (FF ends), the copper
words (MSB first, ending FFFF) and the labels as one pstr string (22, row, col, text, ...). Hatch Fern, Fri 6 Nov 2026."""
from pathlib import Path
import pv4_scene as sc

HERE = Path(__file__).resolve().parent


def db(label, data):
    lines = [f'{label}:']
    for i in range(0, len(data), 16):
        lines.append('        db ' + ','.join(f'0x{b:02X}' for b in data[i:i + 16]))
    return '\n'.join(lines)


def main():
    assert all(r != 0xFF for r, _ in sc.regs())
    regs = [b for pair in sc.regs() for b in pair] + [0xFF]
    words = sc.copper_words()
    assert words.index(0xFFFF) == len(words) - 1
    cop = [b for w in words for b in (w >> 8, w & 0xFF)]
    lab = []
    for row, col, text in sc.labels()[:-1]:                 # finish prints the prompt itself
        lab += [22, row, col] + [ord(c) for c in text]
    lab.append(0)
    out = ['; pv4_data.inc: generated by pv4_data.py from pv4_scene.py; do not edit.',
           f'L2BANK equ {sc.L2_BANK}', f'UATTR equ 0x{sc.ULA_ATTR:02X}',
           db('t_regs', regs), db('t_copper', cop), db('s_labels', lab)]
    (HERE / 'pv4_data.inc').write_text('\n'.join(out) + '\n')
    print(f'pv4_data.inc: regs {len(regs)}, copper {len(cop)}, labels {len(lab)} bytes')


if __name__ == '__main__':
    main()
