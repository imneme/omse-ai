"""Write pv6_data.inc (db tables for pv6.asm) from pv6_scene.py: the register pairs (FF ends), the sprite
palette (256 NR 0x41 values), the pattern (256 bytes) and all 128 sprites' five attribute bytes, in order
from slot 0. Hatch Fern, Fri 6 Nov 2026."""
from pathlib import Path
import pv6_scene as sc

HERE = Path(__file__).resolve().parent


def db(label, data):
    lines = [f'{label}:']
    for i in range(0, len(data), 16):
        lines.append('        db ' + ','.join(f'0x{b:02X}' for b in data[i:i + 16]))
    return '\n'.join(lines)


def main():
    assert all(r != 0xFF for r, _ in sc.regs())
    regs = [b for pair in sc.regs() for b in pair] + [0xFF]
    pats = [b for p in sc.PATTERNS for b in p]
    attrs = [b for idx in range(128) for b in sc.sprites()[idx]]
    assert len(attrs) == 640
    out = ['; pv6_data.inc: generated by pv6_data.py from pv6_scene.py; do not edit.',
           f'NPATBYTES equ {len(pats)}', f'NR15V equ 0x{sc.NR15:02X}', f'STROW equ {sc.STATUS_ROW}',
           db('t_regs', regs), db('t_pal', sc.sprite_palette()), db('t_pats', pats), db('t_attrs', attrs)]
    (HERE / 'pv6_data.inc').write_text('\n'.join(out) + '\n')
    print(f'pv6_data.inc: regs {len(regs)}, palette 256, pattern {len(pats)}, attributes {len(attrs)} bytes')


if __name__ == '__main__':
    main()
